#!/usr/bin/env python3
"""gen_ucode.py -- sdk/radeon-firmware/R200_cp.bin as a C table.

The .bin holds 256 microcode words, each as two big-endian dwords: the
high half (CP_ME_RAM_DATAH) then the low half (CP_ME_RAM_DATAL), the order
Linux's r100_cp_load_microcode writes them. Usage:

    gen_ucode.py <R200_cp.bin> <out.c>      write the table
    gen_ucode.py --check <R200_cp.bin> <out.c>   exit 1 if out.c differs
"""
import hashlib
import struct
import sys

WANT_SHA256 = '2b7b4bf988c3f7c69f98ea2ec6c4155fa85e2c9d5f5aee77912baaf50f5f7bac'


def render(data):
    if len(data) != 2048:
        raise SystemExit(f'gen_ucode: {len(data)} bytes, want 2048')
    sha = hashlib.sha256(data).hexdigest()
    if sha != WANT_SHA256:
        raise SystemExit(f'gen_ucode: SHA-256 {sha} is not the pinned one')
    dw = struct.unpack('>512I', data)
    out = ['/*',
           ' * r2ucode.c -- the R200 CP microcode (GENERATED by tools/gen_ucode.py from',
           ' * sdk/radeon-firmware/R200_cp.bin; do not edit).',
           ' *',
           ' * Copyright 2007-2009 Advanced Micro Devices, Inc. MIT licence: see',
           ' * sdk/radeon-firmware/LICENSE. linux-firmware radeon/R200_cp.bin,',
           f' * SHA-256 {sha}.',
           ' *',
           ' * 256 words, each as (CP_ME_RAM_DATAH, CP_ME_RAM_DATAL).',
           ' */',
           '',
           '#include "r2cp.h"',
           '',
           'const ULONG R2Cp_Microcode[R2CP_UCODE_DWORDS] =',
           '{']
    for i in range(0, 512, 4):
        row = ', '.join(f'0x{v:08x}UL' for v in dw[i:i + 4])
        out.append(f'    {row}{"," if i + 4 < 512 else ""}')
    out += ['};', '']
    return '\n'.join(out)


def main():
    args = sys.argv[1:]
    check = args and args[0] == '--check'
    if check:
        args = args[1:]
    src, dst = args
    text = render(open(src, 'rb').read())
    if check:
        if open(dst).read() != text:
            print(f'gen_ucode: {dst} is stale; rerun tools/gen_ucode.py')
            sys.exit(1)
        return
    open(dst, 'w').write(text)


if __name__ == '__main__':
    main()
