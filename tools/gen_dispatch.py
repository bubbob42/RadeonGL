#!/usr/bin/env python3
"""gen_dispatch.py -- generate a minigl.library dispatch table from the SDK.

Reads `typedef struct MGLDispatchTable { ... }` out of the minigl SDK's
libraries/minigl_dispatch.h (ABI 5: four ULONGs, the currentContext pointer,
then one function pointer per slot, positional) and writes:

  <out>.c  one function per slot, `<prefix><Name>`, with the slot's exact
           signature. Each calls `<count>(slot index)` first. A slot listed
           in --hooks then forwards every argument to `Hook_<Name>`; any other
           slot discards its arguments and returns 0 of its type.
           Then the table itself, `const MGLDispatchTable MiniGLDispatchTable`,
           in header order, and `const char *const <prefix>SlotName[]`.
  <out>.h  the slot count, an index macro per slot (`SLOT_<Name>`), and a
           prototype per hook -- the hook's implementation includes this
           header, so a hook whose signature drifts from the SDK fails to
           compile instead of corrupting the stack.

With --direct UNIMPL (the real library): a hooked slot's table entry IS
`Hook_<Name>` (no wrapper, no counting -- one call less per GL call), and
every other slot is a stub that calls `UNIMPL(slot index)` and returns 0
of its type. No slot is ever NULL (guru 810000FF).

Usage:
  gen_dispatch.py HEADER OUT_BASENAME --prefix Cen_ --count Cen_Hit
                  --hooks NAME[,NAME...] [--flags EXPR] [--context EXPR]
                  [--direct UNIMPL] [--hooks-file FILE]
"""

import argparse
import re
import sys


def read_table(path):
    text = open(path, encoding="latin-1").read()
    m = re.search(r"typedef\s+struct\s+MGLDispatchTable\s*\{(.*?)\}\s*MGLDispatchTable\s*;",
                  text, re.S)
    if not m:
        sys.exit("gen_dispatch: no MGLDispatchTable in %s" % path)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    slots = []
    # A slot: RET (*NAME)(PARAMS);  PARAMS may hold nested (*fn)(...) types.
    pos = 0
    pat = re.compile(r"([A-Za-z_][\w\s\*]*?)\(\s*\*\s*([A-Za-z_]\w*)\s*\)\s*\(")
    while True:
        m = pat.search(body, pos)
        if not m:
            break
        ret = " ".join(m.group(1).split())
        name = m.group(2)
        i = m.end()
        depth = 1
        while depth:
            c = body[i]
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            i += 1
        params = " ".join(body[m.end():i - 1].split())
        semi = body.index(";", i)
        slots.append((ret, name, params))
        pos = semi + 1
    return slots


def split_params(params):
    """Split at top-level commas."""
    out, depth, cur = [], 0, ""
    for c in params:
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        if c == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += c
    if cur.strip():
        out.append(cur.strip())
    return out


def param_name(p):
    m = re.search(r"\(\s*\*\s*([A-Za-z_]\w*)\s*\)", p)       # void (*func)(void)
    if m:
        return m.group(1)
    m = re.search(r"([A-Za-z_]\w*)\s*(\[[^\]]*\])?\s*$", p)
    return m.group(1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("header")
    ap.add_argument("out")
    ap.add_argument("--prefix", default="Cen_")
    ap.add_argument("--count", default="Cen_Hit")
    ap.add_argument("--hooks", default="")
    ap.add_argument("--flags", default="MINIGL_BACKEND_FLAG_STUB")
    ap.add_argument("--context", default="&Cen_CurrentContext")
    ap.add_argument("--include", action="append", default=[])
    ap.add_argument("--direct", default="")
    ap.add_argument("--hooks-file", default="")
    a = ap.parse_args()

    slots = read_table(a.header)
    hooks = set(h for h in a.hooks.split(",") if h)
    if a.hooks_file:
        for line in open(a.hooks_file):
            line = line.split("#")[0].strip()
            if line:
                hooks.add(line)
    names = [s[1] for s in slots]
    missing = sorted(hooks - set(names))
    if missing:
        sys.exit("gen_dispatch: hooks not in the table: " + ", ".join(missing))

    guard = "GEN_DISPATCH_H"
    h = []
    h.append("/* Generated by tools/gen_dispatch.py from %s -- do not edit. */" % a.header)
    h.append("#ifndef %s\n#define %s\n" % (guard, guard))
    h.append("#define DISPATCH_SLOTS %d\n" % len(slots))
    for i, (ret, name, params) in enumerate(slots):
        h.append("#define SLOT_%s %d" % (name, i))
    h.append("")
    for ret, name, params in slots:
        if name in hooks:
            h.append("%s Hook_%s(%s);" % (ret, name, params if params else "void"))
    h.append("\nextern const char *const %sSlotName[DISPATCH_SLOTS];" % a.prefix)
    h.append("\n#endif")

    c = []
    c.append("/* Generated by tools/gen_dispatch.py from %s -- do not edit. */" % a.header)
    c.append("#define MINIGL_LIBRARY_BUILD 1")
    c.append("#include <exec/types.h>")
    c.append("#include <libraries/minigl_dispatch.h>")
    for inc in a.include:
        c.append('#include "%s"' % inc)
    c.append('#include "%s.h"\n' % a.out.split("/")[-1])
    if a.direct:
        c.append("void %s(ULONG slot);\n" % a.direct)
    for i, (ret, name, params) in enumerate(slots):
        plist = split_params(params) if params and params != "void" else []
        pnames = [param_name(p) for p in plist]
        if a.direct and name in hooks:
            continue                    # the table points at the hook itself
        c.append("static %s %s%s(%s)" % (ret, a.prefix, name, params if params else "void"))
        c.append("{")
        c.append("    %s(%d);" % (a.direct if a.direct else a.count, i))
        if name in hooks:
            call = "Hook_%s(%s)" % (name, ", ".join(pnames))
            c.append("    %s%s;" % ("" if ret == "void" else "return ", call))
        else:
            for n in pnames:
                c.append("    (void)%s;" % n)
            if ret != "void":
                c.append("    return (%s)0;" % ret)
        c.append("}\n")
    c.append("const MGLDispatchTable MiniGLDispatchTable =\n{")
    c.append("    MINIGL_DISPATCH_ABI_VERSION,")
    c.append("    sizeof(MGLDispatchTable),")
    c.append("    %s," % a.flags)
    c.append("    0,")
    c.append("    %s," % a.context)
    for i, (ret, name, params) in enumerate(slots):
        entry = ("Hook_" if (a.direct and name in hooks) else a.prefix) + name
        c.append("    %s%s" % (entry, "," if i + 1 < len(slots) else ""))
    c.append("};\n")
    c.append("const char *const %sSlotName[DISPATCH_SLOTS] =\n{" % a.prefix)
    for i, (ret, name, params) in enumerate(slots):
        c.append('    "%s"%s' % (name, "," if i + 1 < len(slots) else ""))
    c.append("};")

    open(a.out + ".h", "w").write("\n".join(h) + "\n")
    open(a.out + ".c", "w").write("\n".join(c) + "\n")
    print("gen_dispatch: %d slots, %d hooks -> %s.c/.h" % (len(slots), len(hooks), a.out))


if __name__ == "__main__":
    main()
